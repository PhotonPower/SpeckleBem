#!/bin/sh
# Sequential queue of speckle_sweep.py cases (WP-S2): one process per case, one after another.
#
#   benchmarks/speckle_sweep_queue.sh OUT PYTHON SIGMA:SEED [SIGMA:SEED ...]
#
# OUT holds pkg/ (a frozen copy of the build-tree package plus speckle_sweep.py, so that the
# source tree can be rebuilt while the queue runs), cases/, rows.txt, one log per case and
# progress.txt. Finished cases (cases/<tag>/row.txt) are skipped, so the queue can be restarted
# with the same arguments. Create OUT/STOP to stop before the next case. Environment overrides:
# L (8e-6), LC (correlation length in metres, 1e-6), LQ (0.99), PLANE_SIZE (4e-3), PLANE_N (161),
# TOL (1e-4), THETA (incidence angle in degrees, 0), WAIST (beam waist in metres; default
# L cos(THETA) / 6 for Si) and PKG (the frozen package directory, OUT/pkg). The log names carry
# only sigma, seed and THETA: use one OUT per series. Start it detached, e.g.
#   nohup sh benchmarks/speckle_sweep_queue.sh "$OUT" /c/msys64/ucrt64/bin/python \
#       250e-9:1 250e-9:2 > "$OUT/queue.out" 2>&1 &
# Do not edit this file while a queue reads it (sh reads scripts incrementally).
set -u
if [ $# -lt 3 ]; then
    echo "usage: $0 OUT PYTHON SIGMA:SEED [SIGMA:SEED ...]" >&2
    exit 2
fi
OUT=$1
PY=$2
shift 2
PKG=${PKG:-$OUT/pkg}
THETA=${THETA:-0}
PROGRESS="$OUT/progress.txt"
echo "$(date '+%Y-%m-%d %H:%M:%S') queue start (theta $THETA deg, pkg $PKG): $*" >> "$PROGRESS"
for c in "$@"; do
    if [ -e "$OUT/STOP" ]; then
        echo "$(date '+%Y-%m-%d %H:%M:%S') STOP file found, queue stopped before $c" >> "$PROGRESS"
        exit 0
    fi
    sigma=${c%%:*}
    seed=${c##*:}
    suffix=""
    if [ "$THETA" != "0" ]; then
        suffix="_t$THETA"
    fi
    echo "$(date '+%Y-%m-%d %H:%M:%S') start sigma=$sigma seed=$seed theta=$THETA" >> "$PROGRESS"
    "$PY" "$PKG/speckle_sweep.py" --pythonpath "$PKG" --L "${L:-8e-6}" --Lc "${LC:-1e-6}" \
        --sigma "$sigma" --seed "$seed" --theta-deg "$THETA" --leaf-quantile "${LQ:-0.99}" \
        --plane-size "${PLANE_SIZE:-4e-3}" --plane-n "${PLANE_N:-161}" \
        --solver-tol "${TOL:-1e-4}" --out "$OUT/cases" --rows "$OUT/rows.txt" \
        --skip-existing ${WAIST:+--waist} ${WAIST:+"$WAIST"} >"$OUT/log_sigma${sigma}_seed${seed}${suffix}.txt" 2>&1
    rc=$?
    echo "$(date '+%Y-%m-%d %H:%M:%S') end sigma=$sigma seed=$seed theta=$THETA exit=$rc" >> "$PROGRESS"
done
echo "$(date '+%Y-%m-%d %H:%M:%S') queue done" >> "$PROGRESS"
